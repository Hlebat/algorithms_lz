import random
v = [] # создали пустой список
while len(v) < 100: #  с помощью цикла while  будем заполнять наш пустой список
    a = random.randint(0, 1000000)
    if a not in v:
        v.append(a)
p = sorted(v) # отсортировали по возрастанию 
print("Список:", p)
n = int(input('Введите число: ')) 
c1 = 0 #  будет показывать сколько шагов сделал поиск
idx1 = -1 # индекс найденного элемента
for i in range(len(p)): # проверяем каждый элемент по очереди
    c1 += 1
    if p[i] == n:
        idx1 = i
        break
if idx1 != -1:
    print("Линейный поиск : Индекс:", idx1, "| Сравнений:", c1)
else:
    print("Линейный поиск : Элемента нет | Сравнений:", c1)
c2 = 0 #  показывает сколько сравнений в бинарном поиске 
l = 0 # показывает какой начальный индекс 
r = len(p) - 1 # показывает последний индекс
idx2 = -1 # индекс найденого элемента
while l <= r:
    c2 += 1
    m = (l + r) // 2 #  находит середнину списка 
    if p[m] == n:
        idx2 = m
        break
    elif n > p[m]: # проверяем где находится элемент относительно середины
        l = m + 1 
    else:
        r = m - 1
if idx2 != -1:
    print("Бинарный поиск : Индекс:", idx2, "| Сравнений:", c2)
else:
    print("Бинарный поиск  : Элемента нет | Сравнений:", c2)