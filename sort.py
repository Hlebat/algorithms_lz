import random
a = [random.randint(0, 1000000) for x in range(100)] # создаем список из 100 рандомных чисел
b = a.copy() # копируем список a
cb = 0  # переменная в торой будет храниться кол-во сравнений
print("Начальный список:", a)
print("СОРТИРОВКА ПУЗЫРЬКОМ:")
i = 0  #  начало пузырька 
while i < len(a) - 1:
    for j in range(len(a) - 1 - i):
        if a[j] < a[j + 1]:  # по убыванию
            a[j], a[j + 1] = a[j + 1], a[j]
            cb += 1  # считаем сравнение
    i += 1
    print(a)
print("Отсортированный список пузырьком:", a)
cs = 0  # счетчик сравнений для выбора
for x in range(len(b)): # начало выборки
    max = x
    for y in range(x + 1, len(b)):
        if b[y] > b[max]:  # ищем максимум для убывания
            max = y
    if max != x:
        b[x], b[max] = b[max], b[x]
        cs += 1  # считаем сравнение
    print(b)
print("Отсортированный список выбором:", b)
print("Количество сравнений пузырьком:", cb)
print("Количество сравнений выбором:", cs)